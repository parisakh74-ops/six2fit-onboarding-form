/** Is a question/sub-field currently part of this user's form? (all matching rules must pass) */
export function isActive(key: string, a: Answers, s: Scope) {
  for (const [re, fn] of RULES) {
    const m = key.match(re);
    if (m && !fn(a, m, s)) return false;
  }
  return true;
}

export function formatValue(key: string, v: any): string {
  const base = key.split(".")[0]!;
  if (key === "ON-04" || key === "ON-06.iso") { const c = byIso(v); return c ? `${flagOf(c.iso)} ${c.fa} (${c.en})` : String(v); }
  const opts: Opt[] | undefined = OPTS[key] ?? (key.startsWith("NU-15.freq") ? OPTS["NU-15.freq"] : OPTS[base]);
  const lab = (x: string) => opts?.find((o) => o[0] === x)?.[1] ?? x;
  if (v === true) return "بله";
  if (v === false) return "خیر";
  if (Array.isArray(v)) return v.map(lab).join("، ");
  if (v && typeof v === "object" && "name" in v) return `📎 ${v.name}`;
  return lab(String(v));
}
